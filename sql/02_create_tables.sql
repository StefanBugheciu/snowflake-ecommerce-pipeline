CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.CUSTOMERS (
    customer_id NUMBER(9, 0) NOT NULL PRIMARY KEY,
    customer_name VARCHAR NOT NULL,
    city VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.PRODUCTS (
    product_id NUMBER(9, 0) NOT NULL PRIMARY KEY,
    product_name VARCHAR NOT NULL,
    category VARCHAR NOT NULL,
    price NUMBER(10, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.ORDERS (
    order_id NUMBER(9, 0) NOT NULL PRIMARY KEY,
    customer_id NUMBER(9, 0) NOT NULL REFERENCES ECOMMERCE_DB.RAW.CUSTOMERS (customer_id),
    product_id NUMBER(9, 0) NOT NULL REFERENCES ECOMMERCE_DB.RAW.PRODUCTS (product_id),
    quantity NUMBER(2, 0) NOT NULL,
    unit_price_at_sale NUMBER(10, 2) NOT NULL,
    order_date DATE NOT NULL
);

CREATE FILE FORMAT IF NOT EXISTS ECOMMERCE_DB.RAW.ECOMMERCE_CSV
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    ESCAPE_UNENCLOSED_FIELD = NONE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    DATE_FORMAT = 'YYYY-MM-DD';

-- Updating this single row serializes publication by concurrent pipeline sessions.
CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.ECOMMERCE_PIPELINE_STATE AS
SELECT 0::NUMBER(18, 0) AS successful_loads;
